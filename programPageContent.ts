function getContentForId(program: Program): ProgramPageContent {
  const id = program.id;
  const custom = BY_PROGRAM_ID[id] || BY_PROGRAM_ID[program.code] || (id.startsWith('07.') ? BY_PROGRAM_ID['07.03.01'] : null) || (id.startsWith('54.03') ? BY_PROGRAM_ID['54.03.01'] : null);
  if (custom) {
    return { ...DEFAULT_CONTENT, ...custom } as ProgramPageContent;
  }
  return DEFAULT_CONTENT;
}

export function getProgramPageContent(program: Program): ProgramPageContent {
  const base = getContentForId(program);
  return {
    ...base,
    targetAudience: base.targetAudience.slice(0, 5),
    whySzu: base.whySzu.slice(0, 4),
    features: base.features.slice(0, 6),
    skills: base.skills.length >= 6 ? base.skills : [...base.skills, ...DEFAULT_CONTENT.skills].slice(0, 10),
    careers: base.careers.length >= 4 ? base.careers : [...base.careers, ...DEFAULT_CONTENT.careers].slice(0, 8),
  };
}
